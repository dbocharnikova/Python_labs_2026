# запрашиваем текст
text=input("Введите текст: ")
# очищаем строку
clean=text.replace(" ", "").lower()
# проверяем на пустую строку
if not clean:
    print("Нет текста")
else:
    # проверяем через обратный срез и выводим результат
    if clean==clean[::-1]:
        print("Палиндром")
    else:
        print("Не палиндром")
