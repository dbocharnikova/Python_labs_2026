count=0 # счетчик отклоненных попыток
# прописывем бесконечный цикл
while True:
   number=int(input("Введите целое число: ")) # запрашиваем данные внутри цикла
   if number>0:
       break # проверка условия и выход из цикла
   count+=1 # подсчет неудачных попыток
# вывод результатов после цикла
print(f"Квадрат числа: {number**2}")
print(f"Количество отклоненных попыток: {count}")