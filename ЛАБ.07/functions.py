def sum_digits(number):  # Принимает целое число, возвращает сумму цифр его модуля. Для нуля возвращает 0.
    n=abs(number)    # Берем модуль числа, чтобы избежать проблем с отрицательными числами.
    if n==0:
        return 0
    total=0
    while n>0:
        total+=n%10  # дает последнюю цифру числа
        n=n//10      # отбрасывает последнюю цифру
    return total

def average(numbers):  # Принимает список чисел, возвращает среднее либо None, если список пуст. Исходный список не изменяется.
    if not numbers:
        return None  # Если список пустой (not [] возвращает True)
    return sum(numbers)/len(numbers)  # Сумма всех элементов деленная на их количество

def normalize_text(text):  #  Возвращает строку в нижнем регистре, без пробельных символов по краям и с одним пробелом между словами.
    return " ".join(text.lower().split())       # делает все буквы строчными и без аргументов разбивает строку по пробелам, автоматически убирая лишние пробелы по краям, собирает список слов обратно в строку через один пробел.

