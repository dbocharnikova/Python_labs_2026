def select_numbers(numbers, threhold):  # Возвращает новый список, где модуль числа не больше порога, сохраняет порядок и повторения, исходный список не меняется.
    return [num for num in numbers if abs(num)<=threhold]     # Используем генератор списка для создания нового списка, перебираем все числа и берем те, чей модуль не больше порога.

